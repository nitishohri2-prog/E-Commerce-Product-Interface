    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

    // Assuming you have a text field named txtSearch for input
    String query = javax.swing.JOptionPane.showInputDialog( this, "Enter product name to search:");
    
    if(query == null){
       return;
    }
    query = query.trim().toLowerCase();
    
    if(query.isEmpty()){
        javax.swing.JOptionPane.showMessageDialog( this, "Please enter a product name to search.");
        return;
    }
    boolean found = false;
    
    //T-Shirt
    boolean match = lblProductName3.getText().toLowerCase().contains(query);
    jPanel6.setVisible(match);
    if(match) found = true;
    
    //Shoes
    match = lblProductName2.getText().toLowerCase().contains(query);
    jPanel8.setVisible(match);
    if(match) found = true;
    
    //Laptop
     match = lblProductName4.getText().toLowerCase().contains(query);
    jPanel9.setVisible(match);
    if(match) found = true;
    
    //TV
     match = lblProductName5.getText().toLowerCase().contains(query);
    jPanel12.setVisible(match);
    if(match) found = true;
    
    //Printer
     match = lblProductName.getText().toLowerCase().contains(query);
    jPanel11.setVisible(match);
    if(match) found = true;
    
    //Monitor
     match = lblProductName7.getText().toLowerCase().contains(query);
    jPanel14.setVisible(match);
    if(match) found = true;
    
    //Mobile Phone
     match = lblProductName8.getText().toLowerCase().contains(query);
    jPanel15.setVisible(match);
    if(match) found = true;
    
    //AC
     match = lblProductName1.getText().toLowerCase().contains(query);
    jPanel10.setVisible(match);
    if(match) found = true;
    
    //Refresh the product area
     jPanel2.revalidate();
    jPanel2.repaint();
    
    if(!found){
        javax.swing.JOptionPane.showMessageDialog( this, "Product not found: " + query);
    }
    
    
   
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnApplyFilterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApplyFilterActionPerformed
       boolean clothing = chkClothing.isSelected();
    boolean electronics = chkElectronics.isSelected();
    boolean homeKitchen = chkHomeKitchen.isSelected();

    // If no category is selected, show all products
    if (!clothing && !electronics && !homeKitchen) {
        
        jPanel6.setVisible(true); // T-Shirt
        jPanel8.setVisible(true); // Shoes
        jPanel9.setVisible(true); // Laptop
        jPanel12.setVisible(true); // TV
        jPanel11.setVisible(true); // Printer
        jPanel14.setVisible(true); // Monitor
        jPanel15.setVisible(true); // Mobile Phone
        jPanel10.setVisible(true); // AC
        
    } else {
        
        // Clothing
        jPanel6.setVisible(clothing); // T-Shirt
        jPanel8.setVisible(clothing); // Shoes
        
        // Electronics
        jPanel9.setVisible(electronics); // Laptop
        jPanel12.setVisible(electronics); // TV
        jPanel11.setVisible(electronics); // Printer
        jPanel14.setVisible(electronics); // Monitor
        jPanel15.setVisible(electronics); // Mobile Phone
        
        // Home & Kitchen
        jPanel10.setVisible(homeKitchen); // AC
    }

    jPanel2.revalidate();
    jPanel2.repaint();
    }

