    private void AddToCart(String ProductName, double ProductPrice, int qty ){
        if(qty <= 0){
            JOptionPane.showMessageDialog(this, "Quantity must be atleast 1.");
            return;
        }
        
        for(CartItem item : cartItems){
            
            if(item.productName.equals(ProductName)){
                item.quantity += qty;
                
                JOptionPane.showMessageDialog(this, ProductName + " quantity updated!\n" + "Quantity: " + item.quantity );
                return;
            }
        }
        //Add new product
        CartItem newItem = new CartItem(ProductName, ProductPrice, qty);
        
        cartItems.add(newItem);
        
        JOptionPane.showMessageDialog(this, "Added to Cart!\n\n" + "Product:" + ProductName + "\nPrice: Rs" + ProductPrice + "\nQuantity: " + qty + "\nTotal: Rs" + newItem.getTotal());
    
    }

