    private void btnEditOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditOrderActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an order first."
    );
    return;
}

int orderId = Integer.parseInt(
        jTable1.getValueAt(selectedRow, 0).toString()
);

String currentStatus =
        jTable1.getValueAt(selectedRow, 5).toString();

String newStatus = javax.swing.JOptionPane.showInputDialog(
        this,
        "Enter new order status:",
        currentStatus
);

if (newStatus == null || newStatus.trim().isEmpty()) {
    return;
}

String sql =
        "UPDATE orders SET status = ? WHERE order_id = ?";

try (
    java.sql.Connection con =
            DatabaseConnection.getConnection();

    java.sql.PreparedStatement stmt =
            con.prepareStatement(sql)
) {

    stmt.setString(1, newStatus);
    stmt.setInt(2, orderId);

    int updated = stmt.executeUpdate();

    if (updated > 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order updated successfully."
        );

        loadOrders();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order could not be updated."
        );
    }

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error updating order:\n" + e.getMessage(),
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();
}  // TODO add your handling code here:
    }//GEN-LAST:event_btnEditOrderActionPerformed

    private void btnDeleteOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteOrderActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an order first."
    );
    return;
}

int orderId = Integer.parseInt(
        jTable1.getValueAt(selectedRow, 0).toString()
);

int confirmation = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this order?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

java.sql.Connection con = null;

try {

    con = DatabaseConnection.getConnection();

    con.setAutoCommit(false);

    // 1. Delete payment connected to this order
    String paymentSql =
            "DELETE FROM payments WHERE order_id = ?";

    java.sql.PreparedStatement paymentStmt =
            con.prepareStatement(paymentSql);

    paymentStmt.setInt(1, orderId);
    paymentStmt.executeUpdate();


    // 2. Delete order item connected to this order
    String itemSql =
            "DELETE FROM order_items WHERE order_id = ?";

    java.sql.PreparedStatement itemStmt =
            con.prepareStatement(itemSql);

    itemStmt.setInt(1, orderId);
    itemStmt.executeUpdate();


    // 3. Delete the order
    String orderSql =
            "DELETE FROM orders WHERE order_id = ?";

    java.sql.PreparedStatement orderStmt =
            con.prepareStatement(orderSql);

    orderStmt.setInt(1, orderId);

    int deleted = orderStmt.executeUpdate();

    if (deleted == 0) {
        throw new Exception("Order could not be found.");
    }


    // Everything succeeded
    con.commit();


    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Order deleted successfully."
    );

    loadOrders();

} catch (Exception e) {

    try {

        if (con != null) {
            con.rollback();
        }

    } catch (Exception rollbackException) {
        rollbackException.printStackTrace();
    }

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Order could not be deleted.\n" +
            e.getMessage(),
            "Delete Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );

    e.printStackTrace();

} finally {

    try {

        if (con != null) {
            con.close();
        }

    } catch (Exception e) {
        e.printStackTrace();
    }
}   // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteOrderActionPerformed

