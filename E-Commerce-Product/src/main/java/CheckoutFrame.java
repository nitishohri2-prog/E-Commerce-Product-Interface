    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     Connection con = null;

    try {

        con = DatabaseConnection.getConnection();

        // Start database transaction
        con.setAutoCommit(false);

        // ---------------------------------------------------------
        // 1. INSERT CUSTOMER
        // ---------------------------------------------------------
        String customerSql =
                "INSERT INTO customers (name, phone, email, address) " +
                "VALUES (?, ?, ?, ?)";

        PreparedStatement customerStmt =
                con.prepareStatement(
                        customerSql,
                        Statement.RETURN_GENERATED_KEYS
                );

        customerStmt.setString(1, txtCustomerName.getText());
        customerStmt.setString(2, txtPhone.getText());
        customerStmt.setString(3, txtEmail.getText());
        customerStmt.setString(4, txtAddress.getText());

        customerStmt.executeUpdate();

        ResultSet customerKeys = customerStmt.getGeneratedKeys();

        int customerId;

        if (customerKeys.next()) {
            customerId = customerKeys.getInt(1);
        } else {
            throw new Exception("Customer ID could not be generated.");
        }


        // ---------------------------------------------------------
        // 2. FIND PRODUCT ID
        // ---------------------------------------------------------
        String productSql =
                "SELECT product_id FROM products WHERE name = ?";

        PreparedStatement productStmt =
                con.prepareStatement(productSql);

        productStmt.setString(1, this.productName);

        ResultSet productResult =
                productStmt.executeQuery();

        int productId;

        if (productResult.next()) {
            productId = productResult.getInt("product_id");
        } else {
            throw new Exception(
                    "Product not found in database: " + this.productName
            );
        }


        // ---------------------------------------------------------
        // 3. INSERT ORDER
        // ---------------------------------------------------------
        String orderSql =
                "INSERT INTO orders " +
                "(customer_id, order_date, total_amount, status) " +
                "VALUES (?, ?, ?, ?)";

        PreparedStatement orderStmt =
                con.prepareStatement(
                        orderSql,
                        Statement.RETURN_GENERATED_KEYS
                );

        orderStmt.setInt(1, customerId);

        orderStmt.setDate(
                2,
                java.sql.Date.valueOf(
                        java.time.LocalDate.now()
                )
        );

        orderStmt.setDouble(3, this.total);

        orderStmt.setString(4, "Pending");

        orderStmt.executeUpdate();

        ResultSet orderKeys =
                orderStmt.getGeneratedKeys();

        int orderId;

        if (orderKeys.next()) {
            orderId = orderKeys.getInt(1);
        } else {
            throw new Exception(
                    "Order ID could not be generated."
            );
        }


        // ---------------------------------------------------------
        // 4. INSERT ORDER ITEM
        // ---------------------------------------------------------
        String itemSql =
                "INSERT INTO order_items " +
                "(order_id, product_id, quantity, price) " +
                "VALUES (?, ?, ?, ?)";

        PreparedStatement itemStmt =
                con.prepareStatement(itemSql);

        itemStmt.setInt(1, orderId);
        itemStmt.setInt(2, productId);
        itemStmt.setInt(3, this.quantity);
        itemStmt.setDouble(4, this.productPrice);

        itemStmt.executeUpdate();


        // ---------------------------------------------------------
        // 5. INSERT PAYMENT
        // ---------------------------------------------------------
        String paymentSql =
                "INSERT INTO payments " +
                "(order_id, customer_name, amount, payment_method, payment_date) " +
                "VALUES (?, ?, ?, ?, ?)";

        PreparedStatement paymentStmt =
                con.prepareStatement(
                        paymentSql,
                        Statement.RETURN_GENERATED_KEYS
                );

        paymentStmt.setInt(1, orderId);
        paymentStmt.setString(2, txtCustomerName.getText());
        paymentStmt.setDouble(3, this.total);
        paymentStmt.setString(4, "Cash");

        // payment_date is VARCHAR in your database
        paymentStmt.setString(
                5,
                java.time.LocalDate.now().toString()
        );

        paymentStmt.executeUpdate();

        ResultSet paymentKeys =
                paymentStmt.getGeneratedKeys();

        int paymentId;

        if (paymentKeys.next()) {
            paymentId = paymentKeys.getInt(1);
        } else {
            throw new Exception(
                    "Payment ID could not be generated."
            );
        }


        // ---------------------------------------------------------
        // 6. COMMIT EVERYTHING
        // ---------------------------------------------------------
        con.commit();


        // ---------------------------------------------------------
        // 7. UPDATE JAVA ORDER LIST
        // ---------------------------------------------------------
        String date =
                java.time.LocalDate.now().toString();

        Order newOrder = new Order(
                orderId,
                txtCustomerName.getText(),
                this.productName,
                this.quantity,
                this.total,
                "Pending",
                date
        );

        OrderManager.addOrder(newOrder);


        // ---------------------------------------------------------
        // 8. UPDATE JAVA PAYMENT LIST
        // ---------------------------------------------------------
        Payment newPayment = new Payment(
                paymentId,
                orderId,
                txtCustomerName.getText(),
                this.total,
                "Cash",
                date
        );

        PaymentManager.addPayment(newPayment);


        // ---------------------------------------------------------
        // 9. SUCCESS MESSAGE
        // ---------------------------------------------------------
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order placed successfully!\n" +
                "Thank you for shopping with us.",
                "Order Confirmation",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        this.dispose();


    } catch (Exception e) {

        // Roll back database transaction if something fails
        try {

            if (con != null) {
                con.rollback();
            }

        } catch (Exception rollbackException) {

            rollbackException.printStackTrace();
        }


        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order could not be placed.\n" +
                e.getMessage(),
                "Order Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();


    } finally {

        try {

            if (con != null) {
                con.close();
            }

        } catch (Exception e) {

            e.printStackTrace();
        }
    }

    }//GEN-LAST:event_jButton1ActionPerformed

