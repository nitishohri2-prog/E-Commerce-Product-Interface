    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
    String name = JOptionPane.showInputDialog(this, "Enter Product Name:");

if (name == null || name.trim().isEmpty()) {
    return;
}

String category = JOptionPane.showInputDialog(this, "Enter Category:");

if (category == null || category.trim().isEmpty()) {
    return;
}

String priceText = JOptionPane.showInputDialog(this, "Enter Price:");

if (priceText == null || priceText.trim().isEmpty()) {
    return;
}

String quantityText = JOptionPane.showInputDialog(this, "Enter Quantity:");

if (quantityText == null || quantityText.trim().isEmpty()) {
    return;
}

try {

    double price = Double.parseDouble(priceText);
    int quantity = Integer.parseInt(quantityText);

    Product product = new Product(
            0,
            name,
            category,
            price,
            quantity
    );

    boolean added = ProductManager.addProduct(product);

    if (added) {

        JOptionPane.showMessageDialog(
                this,
                "Product added successfully!"
        );

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to add product."
        );
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "Please enter a valid price and quantity."
    );
}       // TODO add your handling code here:
    }//GEN-LAST:event_btnAddProductActionPerformed

    private void btnEditProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditProductActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
            this,
            "Please select a product to edit."
    );
    return;
}

int productId = Integer.parseInt(
        jTable1.getValueAt(selectedRow, 0).toString()
);

String currentName = jTable1.getValueAt(selectedRow, 1).toString();
String currentCategory = jTable1.getValueAt(selectedRow, 2).toString();
String currentPrice = jTable1.getValueAt(selectedRow, 3).toString();
String currentQuantity = jTable1.getValueAt(selectedRow, 4).toString();

String name = JOptionPane.showInputDialog(
        this,
        "Enter Product Name:",
        currentName
);

if (name == null || name.trim().isEmpty()) {
    return;
}

String category = JOptionPane.showInputDialog(
        this,
        "Enter Category:",
        currentCategory
);

if (category == null || category.trim().isEmpty()) {
    return;
}

String priceText = JOptionPane.showInputDialog(
        this,
        "Enter Price:",
        currentPrice
);

if (priceText == null || priceText.trim().isEmpty()) {
    return;
}

String quantityText = JOptionPane.showInputDialog(
        this,
        "Enter Quantity:",
        currentQuantity
);

if (quantityText == null || quantityText.trim().isEmpty()) {
    return;
}

try {

    double price = Double.parseDouble(priceText);
    int quantity = Integer.parseInt(quantityText);

    boolean updated = ProductManager.updateProduct(
            productId,
            name,
            category,
            price,
            quantity
    );

    if (updated) {

        JOptionPane.showMessageDialog(
                this,
                "Product updated successfully!"
        );

        loadProducts();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to update product."
        );
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "Please enter a valid price and quantity."
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditProductActionPerformed

    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
            this,
            "Please select a product to delete."
    );
    return;
}

int productId = Integer.parseInt(
        jTable1.getValueAt(selectedRow, 0).toString()
);

String productName = jTable1.getValueAt(selectedRow, 1).toString();

int confirmation = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete " + productName + "?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
);

if (confirmation != JOptionPane.YES_OPTION) {
    return;
}

boolean deleted = ProductManager.deleteProduct(productId);

if (deleted) {

    JOptionPane.showMessageDialog(
            this,
            "Product deleted successfully!"
    );

    loadProducts();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to delete product."
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteProductActionPerformed

