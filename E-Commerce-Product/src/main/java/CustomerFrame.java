    private void btnEditCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditCustomerActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer first.");
    return;
}

int customerId = Integer.parseInt(jTable1.getValueAt(selectedRow, 0).toString());

String name = javax.swing.JOptionPane.showInputDialog(
        this,
        "Enter customer name:",
        jTable1.getValueAt(selectedRow, 1)
);

if (name == null) {
    return;
}

String phone = javax.swing.JOptionPane.showInputDialog(
        this,
        "Enter phone:",
        jTable1.getValueAt(selectedRow, 2)
);

if (phone == null) {
    return;
}

String email = javax.swing.JOptionPane.showInputDialog(
        this,
        "Enter email:",
        jTable1.getValueAt(selectedRow, 3)
);

if (email == null) {
    return;
}

String address = javax.swing.JOptionPane.showInputDialog(
        this,
        "Enter address:",
        jTable1.getValueAt(selectedRow, 4)
);

if (address == null) {
    return;
}

boolean updated = CustomerManager.updateCustomer(
        customerId,
        name,
        phone,
        email,
        address
);

if (updated) {
    javax.swing.JOptionPane.showMessageDialog(this, "Customer updated successfully.");
    loadCustomers();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Failed to update customer.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditCustomerActionPerformed

    private void btnDeleteCustomerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteCustomerActionPerformed
    int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer first.");
    return;
}

int customerId = Integer.parseInt(jTable1.getValueAt(selectedRow, 0).toString());

int confirmation = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this customer?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

boolean deleted = CustomerManager.deleteCustomer(customerId);

if (deleted) {
    javax.swing.JOptionPane.showMessageDialog(this, "Customer deleted successfully.");
    loadCustomers();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete customer.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteCustomerActionPerformed

